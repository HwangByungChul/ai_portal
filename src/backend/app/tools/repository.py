"""Transaction-scoped Tool approvals and owner-only durable receipts."""
from uuid import uuid4
from datetime import date
import psycopg
from psycopg.types.json import Jsonb
from app.db import tenant_transaction
from app.errors import AppError

class ToolRepository:
    def __init__(self,pool,period=date(2026,10,1)):self.pool=pool;self.period=period

    async def _rpc(self,ctx,name,args):
        try:
            async with tenant_transaction(self.pool,ctx) as conn:
                row=await (await conn.execute('SELECT security.'+name+'('+','.join(['%s']*len(args))+') AS data',args)).fetchone()
                return row['data']
        except (psycopg.Error,ValueError) as error:
            code=getattr(error,'sqlstate',None)
            mapped={'A0401':('AUTH_REQUIRED',401),'A0403':('TOOL_NOT_PERMITTED',403),'A0404':('RESOURCE_NOT_FOUND',404),'A0409':('REVISION_CONFLICT',409),'A0429':('TOOL_QUEUE_LIMIT',429),'A0422':('REQUEST_INVALID',422),'22P02':('REQUEST_INVALID',422)}
            raise AppError(*mapped.get(code,('STORAGE_UNAVAILABLE',503))) from None

    async def approval(self,ctx,action,request_id,body,mode='mock'):
        if action=='approve':
            from app.tools.execution import ToolExecutionService
            from app.tools.registry import GLOBAL_TOOL_REGISTRY
            # Descriptor is generated by server code; no caller-controlled URL or schema.
            existing=await self._rpc(ctx,'approval_review_read',(ctx.session_id,ctx.tenant_id,'tool',request_id,Jsonb({}),mode))
            tool_id=existing['request']['tool_id']
            body=body|{'current_descriptor':ToolExecutionService(self,GLOBAL_TOOL_REGISTRY,mode,None).descriptor(tool_id)}
        return await self._rpc(ctx,'tool_approval_control',(ctx.session_id,ctx.tenant_id,action,request_id,Jsonb(body),uuid4()))

    async def execution(self,ctx,action,tool_id,digest,mode,client_id=None,args=None,token=None,result=None,error=''):
        return await self._rpc(ctx,'tool_execution_control',(ctx.session_id,ctx.tenant_id,action,tool_id,digest,mode,client_id,Jsonb(args or {}),token,Jsonb(result if result is not None else {}),error,self.period,uuid4()))
